-- ─── Transacciones ────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS transacciones (
  id          bigint generated by default as identity primary key,
  usuario_id  uuid references auth.users not null default auth.uid(),
  tipo        text    not null check(tipo in ('ingreso', 'gasto', 'deuda')),
  importe     real    not null,
  categoria   text    not null,
  descripcion text,
  fecha       text    not null,
  creado_en   text    default (now()::text)
);

-- ─── Cuentas ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS cuentas (
  id          bigint generated by default as identity primary key,
  usuario_id  uuid references auth.users not null default auth.uid(),
  nombre      text not null,
  tipo        text not null,
  saldo       real not null default 0,
  color       text default 'surface3'
);

-- ─── Deudas ───────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS deudas (
  id          bigint generated by default as identity primary key,
  usuario_id  uuid references auth.users not null default auth.uid(),
  direccion   text not null check(direccion in ('debo', 'me_deben')),
  quien       text not null,
  concepto    text not null,
  total       real not null,
  pagado      real not null default 0,
  vencimiento text,
  creado_en   text default (now()::text)
);

-- ─── Categorías ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS categorias (
  id          bigint generated by default as identity primary key,
  usuario_id  uuid references auth.users not null default auth.uid(),
  nombre      text  not null,
  tipo        text  not null check(tipo in ('ingreso', 'gasto')),
  icono       text  not null default 'category',
  presupuesto real  not null default 0,
  orden       integer not null default 0
);

-- ─── Suscripciones ────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS suscripciones (
  id            bigint generated by default as identity primary key,
  usuario_id    uuid references auth.users not null default auth.uid(),
  nombre        text    not null,
  importe       real    not null,
  ciclo         text    not null check(ciclo in ('mensual', 'anual', 'semanal')),
  proximo_cobro text,
  icono         text    not null default 'subscriptions',
  activa        boolean not null default true,
  creado_en     text    default (now()::text)
);

-- ─── Migración (solo si tus tablas se crearon SIN usuario_id) ─
-- Las filas con usuario_id NULL quedan invisibles con RLS: asígnalas a un usuario
-- (UPDATE transacciones SET usuario_id = '<uuid>' WHERE usuario_id IS NULL;) o bórralas.
ALTER TABLE transacciones ADD COLUMN IF NOT EXISTS usuario_id uuid REFERENCES auth.users DEFAULT auth.uid();
ALTER TABLE cuentas       ADD COLUMN IF NOT EXISTS usuario_id uuid REFERENCES auth.users DEFAULT auth.uid();
ALTER TABLE deudas        ADD COLUMN IF NOT EXISTS usuario_id uuid REFERENCES auth.users DEFAULT auth.uid();
ALTER TABLE categorias    ADD COLUMN IF NOT EXISTS usuario_id uuid REFERENCES auth.users DEFAULT auth.uid();
ALTER TABLE suscripciones ADD COLUMN IF NOT EXISTS usuario_id uuid REFERENCES auth.users DEFAULT auth.uid();

-- ─── Seguridad (RLS) — idempotente ────────────────────────────
-- La anon key es pública (va incrustada en el bundle): TODA la seguridad depende de RLS.
-- Cada usuario autenticado solo puede leer/crear/editar/borrar sus propias filas.

-- Políticas antiguas (versiones previas de este script)
DROP POLICY IF EXISTS "Gestión propia de transacciones" ON transacciones;
DROP POLICY IF EXISTS "Gestión propia de cuentas" ON cuentas;
DROP POLICY IF EXISTS "Gestión propia de deudas" ON deudas;
DROP POLICY IF EXISTS "Gestión propia de categorías" ON categorias;
DROP POLICY IF EXISTS "Gestión propia de suscripciones" ON suscripciones;
DROP POLICY IF EXISTS "Usuarios pueden gestionar sus propias transacciones" ON transacciones;
DROP POLICY IF EXISTS "Usuarios pueden gestionar sus propias cuentas" ON cuentas;
DROP POLICY IF EXISTS "Usuarios pueden gestionar sus propias deudas" ON deudas;
DROP POLICY IF EXISTS "Usuarios pueden gestionar sus propias categorías" ON categorias;
DROP POLICY IF EXISTS "Usuarios pueden gestionar sus propias suscripciones" ON suscripciones;

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['transacciones','cuentas','deudas','categorias','suscripciones'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON public.%I (usuario_id)', 'idx_' || t || '_usuario_id', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', 'propietario_' || t, t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR ALL TO authenticated '
      'USING ((select auth.uid()) = usuario_id) '
      'WITH CHECK ((select auth.uid()) = usuario_id)',
      'propietario_' || t, t);
    -- El rol anónimo no necesita ningún acceso a estas tablas
    EXECUTE format('REVOKE ALL ON public.%I FROM anon', t);
  END LOOP;
END $$;

